import { readdir, readFile, writeFile } from "node:fs/promises";

const diagramDirectory = new URL(
	"../public/images/docs/diagrams/",
	import.meta.url,
);

const darkPalette = new Map([
	["#ffffff", "#0f172a"],
	["#cbd5e1", "#334155"],
	["#0f172a", "#f8fafc"],
	["#64748b", "#94a3b8"],
	["#f1f3f5", "#1e293b"],
	["#495057", "#e2e8f0"],
	["#dbeafe", "#172554"],
	["#336791", "#7dd3fc"],
	["#fff3bf", "#422006"],
	["#f08c00", "#fbbf24"],
	["#ebfbee", "#052e16"],
	["#2f9e44", "#4ade80"],
	["#ede9fe", "#2e1065"],
	["#7048e8", "#c4b5fd"],
	["#ffe3e3", "#450a0a"],
	["#e03131", "#f87171"],
	["#475569", "#cbd5e1"],
]);

const generatedNotice =
	"<!-- Generated by scripts/generate-doc-diagram-themes.ts. -->";
const diagramColorPattern = /#[\da-f]{6}\b/gi;
const lightColorPattern = new RegExp([...darkPalette.keys()].join("|"), "gi");

const createDarkDiagram = (lightSvg: string) => {
	const unsupportedColors = [
		...new Set(
			(lightSvg.match(diagramColorPattern) ?? []).map((color) =>
				color.toLowerCase(),
			),
		),
	].filter((color) => !darkPalette.has(color));
	if (unsupportedColors.length > 0) {
		throw new Error(
			`Unsupported light diagram colors: ${unsupportedColors.join(", ")}`,
		);
	}

	const darkSvg = lightSvg.replace(
		lightColorPattern,
		(lightColor) => darkPalette.get(lightColor.toLowerCase()) ?? lightColor,
	);

	if (darkSvg === lightSvg) {
		throw new Error("Diagram does not contain a supported light theme color");
	}

	return darkSvg.replace("<metadata/>", `<metadata/>${generatedNotice}`);
};

const generateDarkDiagrams = async () => {
	const lightDiagramNames = (await readdir(diagramDirectory))
		.filter((path) => path.endsWith(".svg") && !path.endsWith("-dark.svg"))
		.toSorted();

	for (const lightName of lightDiagramNames) {
		const darkName = lightName.replace(/\.svg$/, "-dark.svg");
		const lightSvg = await readFile(
			new URL(lightName, diagramDirectory),
			"utf8",
		);
		await writeFile(
			new URL(darkName, diagramDirectory),
			createDarkDiagram(lightSvg),
			"utf8",
		);
	}
};

if (import.meta.main) {
	await generateDarkDiagrams();
}

export { createDarkDiagram, generateDarkDiagrams };
