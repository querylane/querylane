package postgres_test

import (
	"github.com/jackc/pgx/v5/pgconn"

	"github.com/querylane/querylane/backend/engine"
	api "github.com/querylane/querylane/backend/protogen/querylane/console/v1alpha1"
)

func (s *PostgresEngineIntegrationTestSuite) TestGeneratedColumnStorageMetadata() {
	ctx := s.T().Context()
	db := s.getTestDBConnection()
	defer db.Close()
	version, err := s.eng.GetServerVersionNum(ctx, db)
	s.Require().NoError(err)
	_, err = db.ExecContext(ctx, `CREATE TABLE generation_kinds (
 id integer GENERATED BY DEFAULT AS IDENTITY,
 source integer NOT NULL,
 stored_value integer GENERATED ALWAYS AS (source * 2) STORED
 )`)
	s.Require().NoError(err)
	if version >= 180000 {
		_, err = db.ExecContext(ctx, `ALTER TABLE generation_kinds
 ADD COLUMN virtual_value integer GENERATED ALWAYS AS (source * 3) VIRTUAL,
 ADD COLUMN default_value integer GENERATED ALWAYS AS (source * 4)`)
		s.Require().NoError(err)
	}
	columns, err := s.eng.ListTableColumns(ctx, db, "public", "generation_kinds")
	s.Require().NoError(err)
	byName := make(map[string]engine.Column, len(columns))
	for _, column := range columns {
		byName[column.Name] = column
	}
	s.Equal(api.GeneratedColumnKind_GENERATED_COLUMN_KIND_UNSPECIFIED, byName["source"].GeneratedKind)
	s.Equal(api.GeneratedColumnKind_GENERATED_COLUMN_KIND_UNSPECIFIED, byName["id"].GeneratedKind)
	s.True(byName["id"].IsIdentity)
	s.False(byName["id"].IsGenerated)
	s.True(byName["stored_value"].IsGenerated)
	s.Equal(api.GeneratedColumnKind_GENERATED_COLUMN_KIND_STORED, byName["stored_value"].GeneratedKind)
	s.Contains(byName["stored_value"].GenerationExpression, "source * 2")
	if version >= 180000 {
		for _, name := range []string{"virtual_value", "default_value"} {
			s.True(byName[name].IsGenerated)
			s.Equal(api.GeneratedColumnKind_GENERATED_COLUMN_KIND_VIRTUAL, byName[name].GeneratedKind)
			s.NotEmpty(byName[name].GenerationExpression)
		}
	}
}

func (s *PostgresEngineIntegrationTestSuite) TestConstraintEnforcementAndValidationMetadata() {
	ctx := s.T().Context()
	db := s.getTestDBConnection()
	defer db.Close()
	version, err := s.eng.GetServerVersionNum(ctx, db)
	s.Require().NoError(err)
	_, err = db.ExecContext(ctx, `CREATE TABLE check_states (n integer,
 CONSTRAINT enforced_check CHECK (n > 0));
 ALTER TABLE check_states ADD CONSTRAINT unvalidated_check CHECK (n < 100) NOT VALID`)
	s.Require().NoError(err)
	if version >= 190000 {
		_, err = db.ExecContext(ctx, `ALTER TABLE check_states
 ADD CONSTRAINT unenforced_check CHECK (n % 2 = 0) NOT ENFORCED`)
		s.Require().NoError(err)
		_, err = db.ExecContext(ctx, `INSERT INTO check_states VALUES (3)`)
		s.Require().NoError(err, "NOT ENFORCED must actually allow a violating row")
	}
	_, err = db.ExecContext(ctx, `INSERT INTO check_states VALUES (-1)`)
	var pgErr *pgconn.PgError
	s.Require().ErrorAs(err, &pgErr)
	s.Equal("23514", pgErr.Code)
	_, err = db.ExecContext(ctx, `INSERT INTO check_states VALUES (101)`)
	s.Require().ErrorAs(err, &pgErr)
	s.Equal("23514", pgErr.Code, "NOT VALID still enforces new rows")
	constraints, err := s.eng.ListTableConstraints(ctx, db, "public", "check_states")
	s.Require().NoError(err)
	byName := make(map[string]engine.TableConstraint, len(constraints))
	for _, constraint := range constraints {
		byName[constraint.Name] = constraint
	}
	for _, name := range []string{"enforced_check", "unvalidated_check"} {
		s.Require().NotNil(byName[name].IsEnforced)
		s.True(*byName[name].IsEnforced)
		s.Require().NotNil(byName[name].IsValidated)
	}
	s.True(*byName["enforced_check"].IsValidated)
	s.False(*byName["unvalidated_check"].IsValidated)
	if version >= 190000 {
		unenforced := byName["unenforced_check"]
		s.Require().NotNil(unenforced.IsEnforced)
		s.False(*unenforced.IsEnforced)
		s.Require().NotNil(unenforced.IsValidated)
		s.False(*unenforced.IsValidated)
		s.Contains(unenforced.Definition, "NOT ENFORCED")
	}
}
